// Load demo: schedules N emails for "right now" on one sender to show throttling.
// Usage: npm run flood -- [count=1000] [hourlyCap=50]
import { pg } from '../src/infra/postgres';
import { kv } from '../src/infra/kv';
import { deliveryQueue } from '../src/delivery/queue';
import { planBatch } from '../src/outbox/plan';

async function run() {
  const count = Number(process.argv[2] ?? 1000);
  const hourlyCap = Number(process.argv[3] ?? 50);

  const owner = (await pg.query('SELECT id, email FROM account ORDER BY created_at LIMIT 1')).rows[0];
  const box = (await pg.query('SELECT id, address FROM mailbox ORDER BY id LIMIT 1')).rows[0];
  if (!owner || !box) throw new Error('Sign in once through the UI and boot the server first.');

  const recipients = Array.from({ length: count }, (_, i) => `lead${i + 1}@example.com`);
  const t = Date.now();
  const result = await planBatch(owner.id, {
    mailboxId: box.id,
    subject: `Load test ${new Date().toISOString()}`,
    body: 'Hello! This message was generated by the flood script.',
    recipients,
    startsAt: new Date(),
    gapSeconds: 0,
    hourlyCap,
  });
  console.log(`Planned ${result.queued} emails for ${owner.email} from ${box.address} in ${Date.now() - t} ms`);
  console.log(`Expect ~${hourlyCap}/hour to send; the rest move to later hour windows as 'throttled'.`);

  await deliveryQueue.close();
  await kv.quit();
  await pg.end();
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
